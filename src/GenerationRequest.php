<?php

declare(strict_types=1);

namespace Delegirium;

/**
 * Всё, что нужно модели, чтобы написать тело функции, и что образует
 * «отпечаток» промпта для кеша. Запрос неизменяем: на ретрае создаётся
 * новый экземпляр с текстом обратной связи от валидатора.
 */
final class GenerationRequest
{
    public function __construct(
        public readonly string $name,
        public readonly string $fqName,
        public readonly string $signature,
        public readonly string $returnType,
        public readonly string $doc,
        public readonly ?string $className,
        public readonly string $namespace,
        public readonly bool $pure = false,
        public readonly ?string $feedback = null,
    ) {
    }

    /**
     * Отпечаток промпта. Меняется при любом изменении контракта или модели,
     * поэтому кеш никогда не отдаёт тело, сгенерированное для другого контракта.
     */
    public function fingerprint(string $providerName, string $model): string
    {
        // Версия протокола промпта: правка текста промпта инвалидирует кеш.
        $protocol = 'delegirium-prompt/1';

        return hash('sha256', implode("\0", [
            $protocol,
            $providerName,
            $model,
            $this->fqName,
            $this->signature,
            $this->returnType,
            $this->doc,
            $this->pure ? 'pure' : 'effectful',
        ]));
    }

    public function withFeedback(string $feedback): self
    {
        return new self(
            $this->name,
            $this->fqName,
            $this->signature,
            $this->returnType,
            $this->doc,
            $this->className,
            $this->namespace,
            $this->pure,
            $feedback,
        );
    }

    public function systemPrompt(): string
    {
        $purity = $this->pure
            ? "- The function is @pure: no I/O, no global state, no time, no randomness, no static variables. Given the same arguments it must return the same value."
            : "- Avoid side effects unless the docblock explicitly requires them.";

        return implode("\n", [
            'You are the body generator of Delegirium, a PHP-derived language where',
            'function bodies are not written by humans but generated by you.',
            '',
            'Rules:',
            '- Emit ONLY the statements that belong inside the function body.',
            '  No <?php tag, no surrounding braces, no markdown fences, no prose.',
            '- The code must be valid PHP 8.1+ and will run in the namespace ' . ($this->namespace !== '' ? $this->namespace : '(global)') . '.',
            '- Never call exec, shell_exec, system, passthru, proc_open, popen, eval,',
            '  or include/require. Never read or write the filesystem or the network.',
            '- Respect the declared parameter and return types exactly.',
            '- Honour the documented edge cases; throw the documented exception types',
            '  with a clear message.',
            $purity,
            '- Prefer short, explicit, deterministic code over clever code.',
        ]);
    }

    public function userPrompt(): string
    {
        $parts = [];

        if ($this->namespace !== '') {
            $parts[] = 'Namespace: ' . $this->namespace;
        }
        if ($this->className !== null) {
            $parts[] = 'Class: ' . $this->className;
        }
        if (trim($this->doc) !== '') {
            $parts[] = "Docblock:\n" . trim($this->doc);
        }

        $parts[] = "Declaration:\n" . $this->signature;
        $parts[] = 'Return type: ' . ($this->returnType !== '' ? $this->returnType : '(mixed)');
        $parts[] = 'Side effects: ' . ($this->pure ? 'forbidden (@pure)' : 'allowed');
        $parts[] = 'Write the body of ' . $this->fqName . '.';

        if ($this->feedback !== null) {
            $parts[] = "Your previous attempt was rejected by the validator:\n" . $this->feedback . "\nFix it and emit the corrected body only.";
        }

        return implode("\n\n", $parts);
    }
}
